export function getCategories() {
  return ["Mixed", ...categoryBank.map((entry) => entry.category)];
}

export function createImposterRound(players, options = {}) {
  if (!Array.isArray(players) || players.length < 3) {
    throw new Error("At least 3 players are required.");
  }

  const shuffledPlayers = [...players];

  for (let i = shuffledPlayers.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));

    [shuffledPlayers[i], shuffledPlayers[j]] = [
      shuffledPlayers[j],
      shuffledPlayers[i],
    ];
  }

  const chosenCategoryName =
    options.category && options.category !== "Mixed"
      ? options.category
      : categoryBank[Math.floor(Math.random() * categoryBank.length)].category;

  const category =
    categoryBank.find((entry) => entry.category === chosenCategoryName) ||
    categoryBank[Math.floor(Math.random() * categoryBank.length)];

  const selectedItem = category.items[Math.floor(Math.random() * category.items.length)];
  const imposterIndex = Math.floor(Math.random() * shuffledPlayers.length);

  return {
    category: category.category,
    secretWord: selectedItem.answer,
    imposterId: shuffledPlayers[imposterIndex],
    clue: selectedItem.clue,
    assignments: shuffledPlayers.map((player, index) => ({
      player,
      role: index === imposterIndex ? "imposter" : "player",
      answer: index === imposterIndex ? null : selectedItem.answer,
      clue: selectedItem.clue,
      category: category.category,
    })),
  };
}

export function getVoteResult(votes, imposterId) {
  const counts = {};

  for (const votedPlayer of Object.values(votes)) {
    counts[votedPlayer] = (counts[votedPlayer] || 0) + 1;
  }

  if (Object.keys(counts).length === 0) {
    return { winner: "tie", eliminated: null };
  }

  const maxVotes = Math.max(...Object.values(counts));

  const leaders = Object.keys(counts).filter(
    (player) => counts[player] === maxVotes
  );

  if (leaders.length !== 1) {
    return { winner: "tie", eliminated: null };
  }

  const eliminated = leaders[0];

  return {
    eliminated,
    winner: eliminated === imposterId ? "players" : "imposter",
  };
}

export function addImposterVote(votes, voter, target, eligiblePlayers) {
  if (!votes || typeof votes !== "object" || !Array.isArray(eligiblePlayers)) return null;
  if (!eligiblePlayers.includes(voter) || !eligiblePlayers.includes(target) || voter === target || Object.hasOwn(votes, voter)) return null;
  return { ...votes, [voter]: target };
}
